const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('whaleagent', Object.freeze({
  dataInfo: () => ipcRenderer.invoke('app:data-info'),
  openDataFolder: () => ipcRenderer.invoke('app:open-data-folder'),
  readSettings: () => ipcRenderer.invoke('settings:read'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  readPrompts: () => ipcRenderer.invoke('prompt:read'),
  savePersona: (persona) => ipcRenderer.invoke('prompt:save-persona', persona),
  saveContentPreferences: (value) => ipcRenderer.invoke('prompt:save-preferences', value),
  interactionStatus: () => ipcRenderer.invoke('interaction:status'),
  resumeInteraction: () => ipcRenderer.invoke('interaction:resume'),
  deleteModelApiKey: (id) => ipcRenderer.invoke('settings:delete-api-key', id),
  testModel: (input) => ipcRenderer.invoke('model:test', input),
  listModels: (input) => ipcRenderer.invoke('model:list', input),
  saveModelProfile: (profile) => ipcRenderer.invoke('model:profile-save', profile),
  deleteModelProfile: (id) => ipcRenderer.invoke('model:profile-delete', id),
  saveModelChain: (chain) => ipcRenderer.invoke('model:chain-save', chain),
  saveReport: (report) => ipcRenderer.invoke('report:save', report),
  listReports: () => ipcRenderer.invoke('report:list'),
  readReport: (name) => ipcRenderer.invoke('report:read', name),
  deleteReport: (name) => ipcRenderer.invoke('report:delete', name),
  openReportFolder: () => ipcRenderer.invoke('report:open-folder'),
  biliStatus: () => ipcRenderer.invoke('bili:status'),
  startBiliLogin: () => ipcRenderer.invoke('bili:login-start'),
  pollBiliLogin: () => ipcRenderer.invoke('bili:login-poll'),
  logoutBili: () => ipcRenderer.invoke('bili:logout'),
  readingStatus: () => ipcRenderer.invoke('bili:reading-status'),
  saveReadingConfig: (config) => ipcRenderer.invoke('bili:reading-config-save', config),
  diaryStatus: () => ipcRenderer.invoke('diary:status'),
  saveDiaryConfig: (config) => ipcRenderer.invoke('diary:config-save', config),
  listDiaries: () => ipcRenderer.invoke('diary:list'),
  writeDiaryNow: () => ipcRenderer.invoke('diary:write'),
  deleteDiaryEntry: (kind, date) => ipcRenderer.invoke('diary:delete-entry', kind, date),
  openDiaryFolder: () => ipcRenderer.invoke('diary:open-folder'),
  searchBiliVideos: (keyword, page, sources) => ipcRenderer.invoke('bili:search', keyword, page, sources),
  analyzeBiliVideos: (input) => ipcRenderer.invoke('bili:analyze', input),
  openBiliVideo: (bvid) => ipcRenderer.invoke('bili:open-video', bvid),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  downloadUpdate: (version) => ipcRenderer.invoke('update:download', version),
  cancelUpdateDownload: () => ipcRenderer.invoke('update:cancel'),
  discardUpdatePackage: () => ipcRenderer.invoke('update:discard'),
  applyUpdate: () => ipcRenderer.invoke('update:apply'),
  openUpdateFolder: () => ipcRenderer.invoke('update:open-folder'),
  openUpdateReleases: () => ipcRenderer.invoke('update:open-releases'),
  startupStatus: () => ipcRenderer.invoke('startup:status'),
  setStartupEnabled: (enabled) => ipcRenderer.invoke('startup:set', enabled === true),
  openStartupSettings: () => ipcRenderer.invoke('startup:open-settings'),
}))
